"""Pack-agnostic LLM agent: builds its prompt and answer schema from the AgentView alone.

The model sees the world rules, the goal, public components, the tools available right now (with
their argument ranges and required predictions) and its own history. It answers with one tool call
in a strict JSON schema generated by knock.core.schema. Nothing here mentions cubes, so the same agent
plays any pack.

Backends: `codex` (Codex CLI on the user's ChatGPT login, sandboxed, tool use flagged as tainted).
"""
from __future__ import annotations

import json
from pathlib import Path

from ..core import AgentView, ToolCall, action_schema, parse_action
from .codex_cli import run_codex

INSTRUCTIONS = """\
You are the agent in Knock, a physics lab. Things look alike but hide their physical properties.
Run experiments with the available tools, reason quantitatively about the readings, then make the
single decisive act. Some tools require a numeric prediction of their result before they run: give
your honest best estimate, because prediction accuracy is scored separately and shows how well you
understand this world. Do NOT run commands, read files, or browse. Answer only with the JSON action."""


GAME_INSTRUCTIONS = """\
You are the agent in a physical simulation game. You see the world through your tools; the physics
(friction, delays, noise, what arrives) is real and partly hidden, so test, measure and fix. Tools
that require a prediction want your honest numeric estimate before they run: prediction accuracy is
scored separately. The game ends when you use the finishing tool or run out of turns. Do NOT run
commands, read files, or browse. Answer only with the JSON action."""


def _tool_lines(tools: list[dict]) -> str:
    out = []
    for t in tools:
        args = ", ".join(
            f"{k} ({p.get('description', '')}; {p.get('minimum')}..{p.get('maximum')})" if "minimum" in p
            else f"{k} ({p.get('description', '')})"
            for k, p in t["args"].get("properties", {}).items()) or "no arguments"
        pred = ""
        if t["prediction"]:
            fields = ", ".join(f"{k} ({p.get('description', '')})" for k, p in t["prediction"]["properties"].items())
            pred = f"\n    prediction {'REQUIRED' if t['prediction_required'] else 'optional'}: {fields}"
        kind = ("DECISIVE ACT, ends the episode" if t["terminal"] else "ENDS THE GAME, final scoring" if t["finishes"]
                else f"costs {t['cost']}" if t["cost"] else "free")
        targets = f"target: a {' or '.join(t['targets'])}" if t["targets"] else "no target"
        out.append(f"- {t['name']} [{kind}; {targets}]: {t['description']}\n    args: {args}{pred}")
    return "\n".join(out)


def _history_lines(history: list[dict]) -> str:
    if not history:
        return "(nothing yet)"
    lines = []
    for i, h in enumerate(history, 1):
        c = h["call"]
        call = f"{c['tool']}({c['target'] or ''}{', ' + json.dumps(c['args']) if c['args'] else ''})"
        if c.get("prediction"):
            call += f" predicted {json.dumps(c['prediction'])}"
        lines.append(f"{i}. {call} -> {json.dumps(h['observation'])}")
    return "\n".join(lines)


def build_prompt(view: AgentView, image_labels: list[str], extra: str = "") -> str:
    task = dict(view.task)
    rules = task.pop("rules", "")
    goal = task.pop("goal")
    imgs = "\n".join(f"  image {i + 1}: {lbl}" for i, lbl in enumerate(image_labels)) or "  (none)"
    left = {k: round(v, 3) for k, v in view.budgets_left.items()}
    has_act = any(t["terminal"] for t in view.tools)
    only_act = has_act and all(t["terminal"] for t in view.tools)
    ask = ("No budget left for other tools: you MUST use the decisive act now." if only_act else
           f"Budgets left: {json.dumps(left)}. Choose your next tool call.")
    state = view.world.get("settings", {}).get("state")
    state_txt = ""
    if state:
        state_txt = "\nCurrent state\n" + "\n".join(f"{k}:\n{v}" if k == "map" else f"{k}: {json.dumps(v)}"
                                                   for k, v in state.items()) + "\n"
    head = INSTRUCTIONS if view.task.get("act") else GAME_INSTRUCTIONS
    return f"""{head}{chr(10) + extra if extra else ""}

World rules
{rules}

Goal
{goal}
Task details: {json.dumps(task)}

Components (what you can see)
{json.dumps(view.world["components"], indent=1)}

{state_txt}
Tools available now
{_tool_lines(view.tools)}

Attached images
{imgs}

Your history
{_history_lines(view.history)}

{ask}
Reply with JSON: tool, target, args (fill the fields your tool uses, null for the rest), prediction
(fill your tool's prediction fields, null for the rest), reasoning (short)."""


class CodexLLMAgent:
    def __init__(self, model: str = "gpt-6-luna", effort: str = "high", log_dir: str | Path | None = None,
                 extra_instructions: str = ""):
        self.extra = extra_instructions
        self.model = model
        self.effort = effort
        self.log_dir = Path(log_dir) if log_dir else None
        self.name = f"codex-{model}-{effort}"
        self._meta: dict = {}

    def reset(self, view: AgentView):
        self._meta = {"model": self.model, "effort": self.effort, "llm_calls": [], "tainted": False}
        self._k = 0

    def episode_meta(self) -> dict:
        return self._meta

    def act(self, view: AgentView) -> ToolCall:
        tools_specs = view.tools
        from ..core import TOOLS
        tools = [TOOLS.get(t["name"]) for t in tools_specs]
        ids = [c["id"] for c in view.world["components"]]
        images = [a for a in view.attachments if a.kind == "image"]
        prompt = build_prompt(view, [a.label for a in images], self.extra)
        stem = (self.log_dir / f"call{self._k:02d}") if self.log_dir else None
        self._k += 1
        res = run_codex(prompt, action_schema(tools, ids), model=self.model, effort=self.effort,
                        image_paths=[a.path for a in images], log_stem=stem)
        tainted = res.tainted_items
        if tainted:
            self._meta["tainted"] = True
        self._meta["llm_calls"].append(res.meta())
        if res.reply is None:
            return ToolCall("__unparseable__", None, reasoning="reply could not be parsed")
        return parse_action(res.reply, tools)
